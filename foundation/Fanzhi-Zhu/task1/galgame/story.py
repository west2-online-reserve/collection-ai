"""《校园·if 恋》—— 剧情、对话与数值数据。

这个模块只存放数据，不包含任何游戏流程逻辑，
这样调整剧情时不需要改动 `game.py` 或 `characters.py`。
"""

from typing import Final, TypedDict


class ChoiceSpec(TypedDict):
    """一个对话选项。"""

    text: str
    reply: str
    affinity: int


class DialogueNode(TypedDict):
    """一次对话：角色的一句台词 + 两个选项。"""

    prompt: str
    choices: dict[str, ChoiceSpec]


class SceneSpec(TypedDict):
    """一次出场场景。"""

    title: str
    intro: tuple[str, ...]
    options: str
    accept: tuple[str, ...]
    reject: tuple[str, ...]
    heroine: str


